#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_parse_compact_peers_valid() {
        /* construct 12 bytes representing two compact IPv4 peers:
           peer 1: 192.168.1.1:6881 (6881 == 0x1ae1)
           peer 2: 10.0.0.2:8080 (8080 == 0x1f90) */
        let data = [
            192, 168, 1, 1, 0x1a, 0xe1,
            10, 0, 0, 2, 0x1f, 0x90,
        ];

        let peers = parse_compact_peers_ipv4(&data).expect("parsing compact peers failed");
        assert_eq!(peers.len(), 2);
        assert_eq!(peers[0], Peer {
            ip: Ipv4Addr::new(192, 168, 1, 1),
            port: 6881,
        });
        assert_eq!(peers[1], Peer {
            ip: Ipv4Addr::new(10, 0, 0, 2),
            port: 8080,
        });
    }

    #[test]
    fn test_parse_compact_peers_invalid_length() {
        /* 5 bytes is not a multiple of 6 */
        let data = [192, 168, 1, 1, 0x1a];
        assert!(parse_compact_peers_ipv4(&data).is_err());
    }
}
