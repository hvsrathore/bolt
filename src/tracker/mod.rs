/* common types, error definitions, and compact peer parsers for tracker communication */

use crate::bencode::BencodeError;
use std::fmt;
use std::net::Ipv4Addr;

/* single IPv4 peer endpoint containing 4-byte IP and 16-bit port */
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct Peer {
    pub ip: Ipv4Addr,
    pub port: u16,
}

impl fmt::Display for Peer {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}:{}", self.ip, self.port)
    }
}

/* state change event signaled to the tracker during announce */
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum AnnounceEvent {
    #[default]
    None,
    Completed,
    Started,
    Stopped,
}

impl AnnounceEvent {
    /* map event to BEP-0015 UDP 32-bit integer constant */
    pub fn to_udp_event_id(self) -> i32 {
        match self {
            Self::None => 0,
            Self::Completed => 1,
            Self::Started => 2,
            Self::Stopped => 3,
        }
    }

    /* map event to BEP-0003 HTTP query string representation */
    pub fn to_http_param_str(self) -> Option<&'static str> {
        match self {
            Self::None => std::option::Option::None,
            Self::Completed => Some("completed"),
            Self::Started => Some("started"),
            Self::Stopped => Some("stopped"),
        }
    }
}

/* parameters required to send an announce request to either HTTP or UDP trackers */
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AnnounceRequest {
    /* 20-byte SHA-1 hash of the torrent info dictionary */
    pub info_hash: [u8; 20],
    /* 20-byte unique identifier generated by client */
    pub peer_id: [u8; 20],
    /* listen on TCP port for inbound peer connections */
    pub port: u16,
    /* total number of bytes uploaded since started */
    pub uploaded: u64,
    /* total number of bytes downloaded since started */
    pub downloaded: u64,
    /* number of remaining bytes needed to complete file */
    pub left: u64,
    /* lifecycle event notification */
    pub event: AnnounceEvent,
    /* maximum number of peers requested from tracker */
    pub num_want: Option<i32>,
}

/* normalized tracker response containing swarm metrics and candidate peers */
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AnnounceResponse {
    /* interval in seconds client should wait between regular announces */
    pub interval: u32,
    /* count of complete peers (seeders) in swarm */
    pub seeders: u32,
    /* count of incomplete peers (leechers) in swarm */
    pub leechers: u32,
    /* parsed peer network addresses */
    pub peers: Vec<Peer>,
}

/* errors encountered during tracker client operations */
#[derive(Debug)]
pub enum TrackerError {
    /* standard I/O network failure */
    Io(std::io::Error),
    /* compact peer byte buffer length is not a multiple of 6 */
    InvalidPeerListLength(usize),
    /* response payload is truncated or structurally invalid */
    InvalidResponse(&'static str),
    /* tracker sent explicit failure message */
    TrackerFailure(String),
    /* handle Bencode deserialization error */
    Bencode(BencodeError),
    /* verify UDP response action code matches expected request action */
    InvalidAction { expected: i32, received: i32 },
    /* verify UDP response transaction ID matches request transaction ID */
    TransactionIdMismatch { expected: u32, received: u32 },
    /* handle HTTP response returning non-200 status code */
    HttpStatus { status_code: u16, reason: String },
    /* announce URL could not be parsed */
    InvalidUrl(String),
}

impl fmt::Display for TrackerError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Io(err) => write!(f, "I/O error: {err}"),
            Self::InvalidPeerListLength(len) => {
                write!(f, "compact peer list length {len} is not a multiple of 6")
            }
            Self::InvalidResponse(msg) => write!(f, "invalid tracker response: {msg}"),
            Self::TrackerFailure(reason) => write!(f, "tracker reported failure: {reason}"),
            Self::Bencode(err) => write!(f, "bencode error: {err}"),
            Self::InvalidAction { expected, received } => {
                write!(f, "invalid UDP action: expected {expected}, received {received}")
            }
            Self::TransactionIdMismatch { expected, received } => {
                write!(f, "UDP transaction ID mismatch: expected {expected}, received {received}")
            }
            Self::HttpStatus { status_code, reason } => {
                write!(f, "HTTP status {status_code}: {reason}")
            }
            Self::InvalidUrl(url) => write!(f, "invalid tracker URL: {url}"),
        }
    }
}

impl std::error::Error for TrackerError {}

impl From<std::io::Error> for TrackerError {
    fn from(err: std::io::Error) -> Self {
        Self::Io(err)
    }
}

impl From<BencodeError> for TrackerError {
    fn from(err: BencodeError) -> Self {
        Self::Bencode(err)
    }
}

/* parse compact 6-byte IPv4 and port peer address entries per BEP-0023.
   each compact peer entry comprises exactly 6 consecutive bytes in network byte order:
   - 4 bytes representing the IPv4 address (octets 0..4)
   - 2 bytes representing the port number in big-endian byte order (octets 4..6).
   this binary layout uses only 6 bytes per peer versus approximately 50 bytes
   for bencoded dictionaries, drastically decreasing tracker bandwidth and memory footprint */
pub fn parse_compact_peers_ipv4(bytes: &[u8]) -> Result<Vec<Peer>, TrackerError> {
    if !bytes.len().is_multiple_of(6) {
        return Err(TrackerError::InvalidPeerListLength(bytes.len()));
    }

    let mut peers = Vec::with_capacity(bytes.len() / 6);
    let (chunks, _) = bytes.as_chunks::<6>();
    for chunk in chunks {
        /* extract 4-byte IPv4 address directly from big-endian network byte slice */
        let ip = Ipv4Addr::new(chunk[0], chunk[1], chunk[2], chunk[3]);

        /* reconstruct 16-bit port from big-endian bytes (chunk[4] as high byte, chunk[5] as low byte) */
        let port = u16::from_be_bytes([chunk[4], chunk[5]]);

        peers.push(Peer { ip, port });
    }

    Ok(peers)
}

